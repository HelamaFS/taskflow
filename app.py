class Linha(dict):
    """Permite acesso tanto por nome quanto por índice, como sqlite3.Row."""
    def __getitem__(self, chave):
        if isinstance(chave, int):
            return list(self.values())[chave]
        return super().__getitem__(chave)


class ResultadoPostgres:
    def __init__(self, cursor, ultimo_id=None):
        self.cursor = cursor
        self.lastrowid = ultimo_id

    def fetchone(self):
        linha = self.cursor.fetchone()
        return Linha(linha) if linha is not None else None

    def fetchall(self):
        return [Linha(linha) for linha in self.cursor.fetchall()]


class ConexaoPostgres:
    def __init__(self):
        self.conexao = psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row)

    def execute(self, sql, parametros=None):
        # Todas as consultas são estáticas; apenas os valores são parametrizados.
        sql = sql.replace("?", "%s")
        insercao_usuario = sql.lstrip().upper().startswith("INSERT INTO USUARIOS")
        if insercao_usuario:
            sql += " RETURNING id"
        cursor = self.conexao.execute(sql, parametros)
        ultimo_id = cursor.fetchone()["id"] if insercao_usuario else None
        return ResultadoPostgres(cursor, ultimo_id)

    def commit(self):
        self.conexao.commit()

    def close(self):
        self.conexao.close()


def conectar_banco():
    if os.environ.get("DATABASE_URL"):
        return ConexaoPostgres()
    conexao = sqlite3.connect(DB_PATH)
    conexao.row_factory = sqlite3.Row
    conexao.execute("PRAGMA foreign_keys = ON")
    return conexao


def criar_banco():
    conexao = conectar_banco()
    if os.environ.get("DATABASE_URL"):
        try:
            conexao.execute("""
                CREATE TABLE IF NOT EXISTS usuarios (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    senha TEXT NOT NULL,
                    tema TEXT NOT NULL DEFAULT 'claro',
                    cor TEXT NOT NULL DEFAULT 'azul'
                )
            """)
            conexao.execute("""
                CREATE TABLE IF NOT EXISTS tarefas (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    descricao TEXT NOT NULL,
                    concluida INTEGER NOT NULL DEFAULT 0,
                    data_entrega TEXT,
                    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE
                )
            """)
            # Compatibilidade com eventuais tabelas criadas anteriormente.
            conexao.execute("ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS tema TEXT NOT NULL DEFAULT 'claro'")
            conexao.execute("ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS cor TEXT NOT NULL DEFAULT 'azul'")
            conexao.execute("ALTER TABLE tarefas ADD COLUMN IF NOT EXISTS data_entrega TEXT")
            conexao.execute("ALTER TABLE tarefas ADD COLUMN IF NOT EXISTS usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE")
            conexao.commit()
        finally:
            conexao.close()
        return

    # Mantém o SQLite local e suas migrações existentes.
    conexao.execute("""
        CREATE TABLE IF NOT EXISTS usuarios (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nome TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            senha TEXT NOT NULL,
            tema TEXT NOT NULL DEFAULT 'claro',
            cor TEXT NOT NULL DEFAULT 'azul'
        )
    """)
    conexao.execute("""
        CREATE TABLE IF NOT EXISTS tarefas (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            descricao TEXT NOT NULL,
            concluida INTEGER DEFAULT 0,
            data_entrega TEXT
        )
    """)
    colunas = [coluna["name"] for coluna in conexao.execute("PRAGMA table_info(tarefas)").fetchall()]
    if "usuario_id" not in colunas:
        conexao.execute("ALTER TABLE tarefas ADD COLUMN usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE")
    if "data_entrega" not in colunas:
        conexao.execute("ALTER TABLE tarefas ADD COLUMN data_entrega TEXT")
    colunas_usuarios = [coluna["name"] for coluna in conexao.execute("PRAGMA table_info(usuarios)").fetchall()]
    if "tema" not in colunas_usuarios:
        conexao.execute("ALTER TABLE usuarios ADD COLUMN tema TEXT NOT NULL DEFAULT 'claro'")
    if "cor" not in colunas_usuarios:
        conexao.execute("ALTER TABLE usuarios ADD COLUMN cor TEXT NOT NULL DEFAULT 'azul'")
    conexao.commit()
    conexao.close()

if not os.environ.get("DATABASE_URL"):
    criar_banco()


